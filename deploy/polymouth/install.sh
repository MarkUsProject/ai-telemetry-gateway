#!/usr/bin/env bash
# Builds the gateway into ${INSTALL_DIR} from this repo checkout.
#
# Usage: install.sh <staging.conf|rehearsal.conf>
#
# Runs as Mateo. Safe to re-run, even with the service up: it refreshes code,
# config, seeds and the venv, and keeps secrets.env, caches and logs.
# make-db-setup.sh writes Dean's database setup file separately.
#
# Layout it produces (see the staging plan for the reasoning):
#   app/              config.yaml + the 6 gateway modules from lib/
#   db/               migrate.sh, migrations, rendered staging seeds
#   service/          daemontools run scripts
#   venv/             Python venv with LiteLLM and the module dependencies
#   var/home/         HOME for the service: Prisma's Node and engine caches
#   var/              dead-letter spool
#   logs/             multilog output
#   runtime.env       non-secret settings the run script loads
#   secrets.env       keys and passwords (make-secrets.sh)

source "$(dirname "$0")/lib.sh"
conf="${1:-}"
load_conf "$conf"

# New files stay with Mateo plus the service group.
umask 007

# ---------- Folder ----------
if [[ ! -d "$INSTALL_DIR" ]]; then
  # The rehearsal folder sits under /data/otelcol, which Mateo owns. The
  # staging folder sits under /data, which Dean creates in Email 1.
  mkdir "$INSTALL_DIR" 2>/dev/null \
    || die "cannot create $INSTALL_DIR. Has Dean run Email 1?"
  chgrp "$SERVICE_USER" "$INSTALL_DIR"
  chmod 2750 "$INSTALL_DIR"
fi
[[ -w "$INSTALL_DIR" ]] || die "$INSTALL_DIR is not writable by $(id -un)"

log "creating layout in $INSTALL_DIR"
mkdir -p "$INSTALL_DIR"/{app,db/migrations,db/seed,deploy,service/log,var/home,logs}

# ---------- Python venv ----------
venv="$INSTALL_DIR/venv"
if [[ ! -x "$venv/bin/python" ]]; then
  log "creating venv with $PYTHON"
  "$PYTHON" -m venv "$venv"
fi
log "installing litellm[proxy,extra-proxy]==$LITELLM_VERSION"
"$venv/bin/pip" install --quiet --no-cache-dir --upgrade pip
# extra-proxy supplies prisma, which the proxy needs to reach its database.
# The gateway modules' own dependencies come from requirements.txt; its
# test-runner entry (pytest) stays out of the service venv.
mapfile -t module_deps < <(grep -E '^(cryptography|psycopg)' "$REPO_DIR/requirements.txt")
"$venv/bin/pip" install --quiet --no-cache-dir \
  "litellm[proxy,extra-proxy]==${LITELLM_VERSION}" "${module_deps[@]}"

# ---------- App code and config ----------
log "copying gateway modules and $MODEL_CONFIG"
cp "$REPO_DIR"/lib/*.py "$INSTALL_DIR/app/"
cp "$KIT_DIR/config/$MODEL_CONFIG" "$INSTALL_DIR/app/config.yaml"

log "copying migrations"
cp "$REPO_DIR/db/migrate.sh" "$INSTALL_DIR/db/"
cp "$REPO_DIR"/db/migrations/*.sql "$INSTALL_DIR/db/migrations/"

log "copying service scripts"
cp "$KIT_DIR/service/run" "$INSTALL_DIR/service/run"
cp "$KIT_DIR/service/log/run" "$INSTALL_DIR/service/log/run"
chmod 750 "$INSTALL_DIR/service/run" "$INSTALL_DIR/service/log/run" "$INSTALL_DIR/db/migrate.sh"

# Non-secret runtime settings. service/run and service/log/run load this.
cat > "$INSTALL_DIR/runtime.env" <<EOF
# Generated by install.sh from $(basename "$conf"). Edits get overwritten.
SERVICE_USER=${SERVICE_USER}
LISTEN_HOST=${LISTEN_HOST}
LISTEN_PORT=${LISTEN_PORT}
STORE_MODEL_IN_DB=True
AITG_DEAD_LETTER_PATH=${INSTALL_DIR}/var/dead-letter.jsonl
AITG_MAX_TOKENS_CEILING=${MAX_TOKENS_CEILING}
EOF

# ---------- Secrets and seeds ----------
"$KIT_DIR/make-secrets.sh" "$conf"

log "rendering staging seeds"
export MARKUS_INSTANCE COURSE_IDS COURSE_BUDGET_CAD COURSE_ALERT_CAD \
       PERIOD_CODE PERIOD_NAME PERIOD_START PERIOD_END TERM_BUDGET_CAD
rm -f "$INSTALL_DIR"/db/seed/*.sql
for tmpl in "$KIT_DIR"/templates/0*.sql.tmpl; do
  python3 "$KIT_DIR/render.py" "$tmpl" "$INSTALL_DIR/db/seed/$(basename "$tmpl" .tmpl)"
done

# ---------- Prisma client ----------
# LiteLLM imports a generated Prisma client. Generating it writes absolute
# paths to the query engine under HOME, so HOME must be the service's HOME,
# not Mateo's private one. So the folder stays where it is after install.
log "generating the Prisma client"
schema="$("$venv/bin/python" -c 'import litellm, pathlib; print(pathlib.Path(litellm.__file__).parent / "proxy" / "schema.prisma")')"
(
  export HOME="$INSTALL_DIR/var/home"
  export PATH="$venv/bin:/local/bin:/usr/bin:/bin"
  cd "$(dirname "$schema")"
  prisma generate --schema "$schema" >/dev/null
)

# ---------- Permissions ----------
# Group members read and run everything; var/ and logs/ take group writes
# (setgid keeps new files in the group). The pass changes Mateo's own files:
# once the service runs, autotst owns its logs and caches, root owns
# service/supervise, and chmod on those fails.
log "setting group permissions"
mine=(find "$INSTALL_DIR" -user "$(id -un)" -not -path '*/supervise*')
"${mine[@]}" -exec chgrp "$SERVICE_USER" {} +
"${mine[@]}" -exec chmod g+rX,o-rwx {} +
"${mine[@]}" \( -path "$INSTALL_DIR/var*" -o -path "$INSTALL_DIR/logs*" \) -exec chmod g+w {} +
"${mine[@]}" -type d \( -path "$INSTALL_DIR/var*" -o -path "$INSTALL_DIR/logs*" \) -exec chmod g+s {} +
# secrets.env keeps its own mode (640, set by make-secrets.sh).
chmod 640 "$INSTALL_DIR/secrets.env"

log "done. Next: see deploy/polymouth/README.md for the steps that follow."
